module  color_mapper ( input  logic [9:0] BallX, BallY, DrawX, DrawY, Ball_size,
                       input  logic [7:0] pipe_width,
                       input logic [9:0] pipe1_height, pipe2_height, pipe_gap,
                       input logic signed [11:0] pipe1_xpos, pipe2_xpos,
                       
                       input logic [7:0] cloud1_width, cloud2_width,
                       input logic [9:0] cloud1_height, cloud2_height, // bottom part

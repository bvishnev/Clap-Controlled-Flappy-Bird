    parameter [9:0] X_Min = 0;       // Leftmost point on the X axis
    parameter [9:0] X_Max = 639;     // Rightmost point on the X axis
    parameter [9:0] Y_Min = 0;       // Topmost point on the Y axis
    parameter [9:0] Y_Max = 479;     // Bottommost point on the Y axis
    
    logic ball_on, pipe_on, cloud_on;
	 
 /* 

     New Ball: Generates (pixelated) circle by using the standard circle formula.  Note that while 
     this single line is quite powerful descriptively, it causes the synthesis tool to use up three
     of the 120 available multipliers on the chip!  Since the multiplicants are required to be signed,
	  we have to first cast them from logic to int (signed by default) before they are multiplied). */
	  
    int DistX, DistY, Size;
    assign DistX = DrawX - BallX;
    assign DistY = DrawY - BallY;
    assign Size = Ball_size;
    
    
  
    always_comb
    begin:Ball_on_proc
        if ( (DistX*DistX + DistY*DistY) <= (Size * Size) )
            ball_on = 1'b1;
            
        else 
            ball_on = 1'b0;
     end 
     
     always_comb begin
     
        pipe_on = 1'b0; // default
        
        if($signed({2'b0, DrawX}) >= pipe1_xpos && $signed({2'b0, DrawX}) <= $signed(pipe1_xpos + pipe_width)) begin
            if(DrawY >= (Y_Max - pipe1_height) || DrawY <= (Y_Max - pipe1_height - pipe_gap)) begin
                pipe_on = 1'b1;
            end
        end
        
        if($signed({2'b0, DrawX}) >= pipe2_xpos && $signed({2'b0, DrawX}) <= $signed(pipe2_xpos + pipe_width)) begin
            if(DrawY >= (Y_Max - pipe2_height) || DrawY <= (Y_Max - pipe2_height - pipe_gap)) begin
                pipe_on = 1'b1;
            end
        end
        
     end
     
     always_comb begin
     
        cloud_on = 1'b0; // default
        
        if($signed({2'b0, DrawX}) >= cloud1_xpos && $signed({2'b0, DrawX}) <= $signed(cloud1_xpos + cloud1_width)) begin
            if(DrawY >= cloud1_ypos - cloud1_height && DrawY <= cloud1_ypos) begin
                cloud_on = 1'b1;
            end
        end
        
        if($signed({2'b0, DrawX}) >= cloud2_xpos && $signed({2'b0, DrawX}) <= $signed(cloud2_xpos + cloud2_width)) begin
            if(DrawY >= cloud2_ypos - cloud2_height && DrawY <= cloud2_ypos) begin
                cloud_on = 1'b1;
            end
        end
        
     end
     

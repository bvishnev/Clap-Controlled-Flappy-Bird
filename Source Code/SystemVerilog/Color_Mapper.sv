    begin:RGB_Display

        digit_place = 2'd3 - DrawX / 16;
        digit = score_bcd[digit_place*4 +: 4];
        row = digits_bitmaps[digit*32+DrawY];
        digit_bit = row[15-(DrawX % 16)];
        if(DrawX <= 10'd63 && DrawY <= 10'd32 && digit_bit == 1'b1) begin // score
            Red = 4'hf; 
            Green = 4'hf;
            Blue = 4'hf;
        end
        else if(pipe_on == 1'b1) begin
            Red = 4'h0;
            Green = 4'hf;
            Blue = 4'h0;
        end
        else if (ball_on == 1'b1) begin 
            if(dead) begin // red if dead
                Red = 4'hf;
                Green = 4'h0;
                Blue = 4'h0;
            end else begin // yellow if start or active
                relative_x_coord = DrawX - (BallX-Ball_size);
                relative_y_coord = DrawY - (BallY-Ball_size);
                bird_pixel_row_major_order = relative_y_coord*32 + relative_x_coord;
                
                  
                Red = bird_bitmap[bird_pixel_row_major_order][11:8];
                Green = bird_bitmap[bird_pixel_row_major_order][7:4];
                Blue = bird_bitmap[bird_pixel_row_major_order][3:0];
            end
        end   
        else if (cloud_on == 1'b1) begin
            Red = 4'hf;
            Green = 4'hf;
            Blue = 4'hf;
        end
        else begin  // background
            Red = 4'd8;
            Green = 4'd13;
            Blue = 4'd14;
        end      
    end 
    

    always_ff @(posedge pixel_clk) begin
        if(new_frame) begin
            crash_temp <= 1'b0;
        end
        else if((ball_on & pipe_on)) begin
            crash_temp <= 1'b1;
        end
    end
    
    assign crash = crash_temp | (BallY + Ball_size >= Y_Max);
    
